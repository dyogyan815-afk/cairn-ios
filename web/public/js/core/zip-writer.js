// Streaming-friendly ZIP writer. Raw-copies original compressed bytes (no recompression, so contents stay byte-identical)
// and assembles the result as a Blob of parts (slices of the source file are references, not memory copies).
import { te, AppError } from './util.js';
import { crc32 } from './crc32.js';

const U32 = 0xffffffff;

export function dosDateTime(d = new Date()) {
  const y = Math.max(1980, d.getFullYear());
  return {
    time: (d.getHours() << 11) | (d.getMinutes() << 5) | (d.getSeconds() >> 1),
    date: ((y - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate(),
  };
}

export class ZipWriter {
  constructor() {
    this.parts = [];
    this.offset = 0;
    this.central = [];
    this.paths = new Map();
    this.count = 0;
  }

  _add(part, len) { this.parts.push(part); this.offset += len; }

  _entry({ nameBytes, flags, method, time, date, crc, csize, usize, madeBy, needed, intAttr, extAttr, dataParts }) {
    const big = csize >= U32 || usize >= U32;
    const offBig = this.offset >= U32;
    const nl = nameBytes.length;
    let lextra = new Uint8Array(0);
    if (big) {
      lextra = new Uint8Array(20);
      const d = new DataView(lextra.buffer);
      d.setUint16(0, 1, true); d.setUint16(2, 16, true);
      d.setBigUint64(4, BigInt(usize), true); d.setBigUint64(12, BigInt(csize), true);
    }
    const lh = new Uint8Array(30 + nl + lextra.length);
    const d = new DataView(lh.buffer);
    const f = flags & ~0x8; // sizes are known: no data descriptor
    const ver = big ? Math.max(needed || 20, 45) : (needed || 20);
    d.setUint32(0, 0x04034b50, true); d.setUint16(4, ver, true); d.setUint16(6, f, true); d.setUint16(8, method, true);
    d.setUint16(10, time, true); d.setUint16(12, date, true); d.setUint32(14, crc, true);
    d.setUint32(18, big ? U32 : csize, true); d.setUint32(22, big ? U32 : usize, true);
    d.setUint16(26, nl, true); d.setUint16(28, lextra.length, true);
    lh.set(nameBytes, 30); lh.set(lextra, 30 + nl);
    const localOffset = this.offset;
    this._add(lh, lh.length);
    for (const p of dataParts) this._add(p, p.size ?? p.length);
    this.central.push({ nameBytes, f, method, time, date, crc, csize, usize, madeBy, ver, intAttr, extAttr, localOffset, big, offBig });
    this.count++;
  }

  /** Raw-copy an entry from a source archive without recompressing. */
  addRaw(path, srcBlob, e, { keepRawName = false } = {}) {
    if (e.dataOffset < 0) throw new AppError('bad-entry', `Cannot copy "${e.name}": damaged local header.`);
    const nameBytes = keepRawName ? e.nameRaw : te.encode(path);
    const flags = keepRawName ? e.flags : ((e.flags & ~0x800) | (/[^\x00-\x7f]/.test(path) ? 0x800 : 0));
    this._entry({
      nameBytes, flags, method: e.method, time: e.time, date: e.date, crc: e.crc,
      csize: e.csize, usize: e.usize, madeBy: e.madeBy, needed: e.needed, intAttr: e.intAttr, extAttr: e.extAttr,
      dataParts: e.csize ? [srcBlob.slice(e.dataOffset, e.dataOffset + e.csize)] : [],
    });
    this.paths.set(path, (this.paths.get(path) || 0) + 1);
  }

  /** Add generated bytes (stored). */
  addBytes(path, bytes, { mtime = new Date(), mode = 0o100644 } = {}) {
    if (typeof bytes === 'string') bytes = te.encode(bytes);
    const { time, date } = dosDateTime(mtime);
    this._entry({
      nameBytes: te.encode(path), flags: /[^\x00-\x7f]/.test(path) ? 0x800 : 0, method: 0, time, date,
      crc: crc32(bytes), csize: bytes.length, usize: bytes.length, madeBy: (3 << 8) | 20, needed: 20, intAttr: 0,
      extAttr: ((mode & 0xffff) << 16) >>> 0, dataParts: bytes.length ? [bytes] : [],
    });
    this.paths.set(path, (this.paths.get(path) || 0) + 1);
  }

  addDirectory(path, srcEntry) {
    if (!path.endsWith('/')) path += '/';
    const { time, date } = srcEntry ? { time: srcEntry.time, date: srcEntry.date } : dosDateTime();
    this._entry({
      nameBytes: te.encode(path), flags: 0x800 * +/[^\x00-\x7f]/.test(path), method: 0, time, date, crc: 0, csize: 0, usize: 0,
      madeBy: srcEntry ? srcEntry.madeBy : (3 << 8) | 20, needed: 20, intAttr: 0,
      extAttr: srcEntry ? srcEntry.extAttr : ((0o040755 << 16) | 0x10) >>> 0, dataParts: [],
    });
    this.paths.set(path, 1);
  }

  finish() {
    const cdStart = this.offset;
    const chunks = [];
    let cdSize = 0;
    for (const c of this.central) {
      const needSizes = c.big, needOff = c.offBig;
      const extraLen = (needSizes || needOff) ? 4 + (needSizes ? 16 : 0) + (needOff ? 8 : 0) : 0;
      const b = new Uint8Array(46 + c.nameBytes.length + extraLen);
      const d = new DataView(b.buffer);
      d.setUint32(0, 0x02014b50, true); d.setUint16(4, c.madeBy, true);
      d.setUint16(6, (needSizes || needOff) ? Math.max(c.ver, 45) : c.ver, true);
      d.setUint16(8, c.f, true); d.setUint16(10, c.method, true); d.setUint16(12, c.time, true); d.setUint16(14, c.date, true);
      d.setUint32(16, c.crc, true);
      d.setUint32(20, needSizes ? U32 : c.csize, true); d.setUint32(24, needSizes ? U32 : c.usize, true);
      d.setUint16(28, c.nameBytes.length, true); d.setUint16(30, extraLen, true); d.setUint16(32, 0, true);
      d.setUint16(34, 0, true); d.setUint16(36, c.intAttr, true); d.setUint32(38, c.extAttr, true);
      d.setUint32(42, needOff ? U32 : c.localOffset, true);
      b.set(c.nameBytes, 46);
      if (extraLen) {
        let q = 46 + c.nameBytes.length;
        d.setUint16(q, 1, true); d.setUint16(q + 2, extraLen - 4, true); q += 4;
        if (needSizes) { d.setBigUint64(q, BigInt(c.usize), true); d.setBigUint64(q + 8, BigInt(c.csize), true); q += 16; }
        if (needOff) d.setBigUint64(q, BigInt(c.localOffset), true);
      }
      chunks.push(b); cdSize += b.length;
    }
    const total = this.central.length;
    const need64 = total >= 0xffff || cdStart >= U32 || cdSize >= U32;
    const tailParts = [];
    if (need64) {
      const z = new Uint8Array(56 + 20);
      const d = new DataView(z.buffer);
      d.setUint32(0, 0x06064b50, true); d.setBigUint64(4, 44n, true); d.setUint16(12, 45, true); d.setUint16(14, 45, true);
      d.setBigUint64(24, BigInt(total), true); d.setBigUint64(32, BigInt(total), true);
      d.setBigUint64(40, BigInt(cdSize), true); d.setBigUint64(48, BigInt(cdStart), true);
      d.setUint32(56, 0x07064b50, true); d.setBigUint64(64, BigInt(cdStart + cdSize), true); d.setUint32(72, 1, true);
      tailParts.push(z);
    }
    const e = new Uint8Array(22);
    const d = new DataView(e.buffer);
    d.setUint32(0, 0x06054b50, true);
    d.setUint16(8, need64 ? 0xffff : total, true); d.setUint16(10, need64 ? 0xffff : total, true);
    d.setUint32(12, need64 ? U32 : cdSize, true); d.setUint32(16, need64 ? U32 : cdStart, true);
    tailParts.push(e);
    return new Blob([...this.parts, ...chunks, ...tailParts], { type: 'application/zip' });
  }
}
