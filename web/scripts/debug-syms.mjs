import fs from 'node:fs';
const m = await import('../public/js/core/deps.js');
console.log('rpath:', m.isSystemLib('@rpath/MySDK.framework/MySDK'));
console.log('swiftCore:', m.isSystemLib('libswiftCore.dylib'));
console.log('usr/lib:', m.isSystemLib('/usr/lib/libSystem.dylib'));
console.log('UIKit path:', m.isSystemLib('/System/Library/Frameworks/UIKit.framework/UIKit'));
const { scanIPA } = await import('../public/js/core/ipa.js');
const blob = new Blob([fs.readFileSync(new URL('../tests/fixtures/small.ipa', import.meta.url))]);
const model = await scanIPA(blob, { hash: false });
console.log('exec:', model.app.executablePath, model.app.executableSize);
const { entryBytes } = await import('../public/js/core/zip-reader.js');
const exec = model.files.find((f) => f.path === model.app.executablePath);
const { bytes } = await entryBytes(blob, exec.entry, exec.size);
const { parseMachO } = await import('../public/js/core/macho.js');
const mm = parseMachO(bytes);
const sl = mm.slices.find((s) => s.ok);
console.log('symtab:', JSON.stringify(sl.symtab), 'sampleSymbols:', sl.sampleSymbols ? sl.sampleSymbols.length : null, 'encrypted:', sl.encrypted);
const { readSymbols } = await import('../public/js/core/symbols.js');
const syms = readSymbols(bytes, sl);
console.log('readSymbols:', syms.ok, syms.error || '', syms.count);
